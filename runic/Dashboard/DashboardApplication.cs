using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.DependencyInjection.Extensions;
using NixManager.Configuration;
using NixManager.Domain;
using NixManager.Operations;
using NixManager.Setup;
using Runic.Application.Views;
using Runic.Application.Views.Desktop;
using Runic.Desktop;

namespace NixManager.Dashboard;

/// <summary>
/// Opens the dashboard Window. <see cref="OpenAsync"/> works from any process that hosts the backend: the per-user
/// daemon of D025.2, which opens and raises the Window in its own process (<see cref="Daemon.DaemonApplication"/>), and
/// <c>nix-manager ui</c> on its own (<see cref="Run"/>) when no running instance can be used.
/// </summary>
public static class DashboardApplication
{
    /// <summary>The size the dashboard opens with.</summary>
    public static RunicWindowOptions WindowOptions => new() { Width = 1180, Height = 800 };

    /// <summary>Registers the dashboard Window for a process that registered the backend (<see cref="BackendServices"/>).</summary>
    public static IServiceCollection AddNixManagerDashboard(this IServiceCollection services)
    {
        services.TryAddScoped<DashboardViewModel>();
        // Generated by the build: the Window and View Bridges.
        services.AddRunicViews();
        return services;
    }

    /// <summary>Opens the dashboard and returns when it closes. A running operation keeps running (D025.1).</summary>
    public static async Task ShowAsync(IRunicWindowHost host, CancellationToken cancellationToken = default)
    {
        await using var window = await OpenAsync(host, cancellationToken);
        await window.WaitForCloseAsync();
    }

    /// <summary>Opens the dashboard and returns its Window, which the daemon brings forward on a later launch.</summary>
    public static async Task<IRunicWindow> OpenAsync(IRunicWindowHost host, CancellationToken cancellationToken = default) =>
        await host.OpenWindowAsync<DashboardWindow>(WindowOptions, cancellationToken);

    /// <summary>The Desktop host as the dashboard and the daemon start it.</summary>
    public static DesktopHostOptions HostOptions() => new()
    {
        // WebKitGTK 4.1 through GTK 3; Runic Desktop falls back to an installed browser without it.
        Linux = new() { EmbeddedBackend = LinuxEmbeddedBackend.Gtk3WebKit41 },
        DiagnosticSink = diagnostic =>
            Console.Error.WriteLine($"{diagnostic.Severity} {diagnostic.Code}: {diagnostic.Message} {diagnostic.Remediation}".TrimEnd()),
        // The process outlives its Window while an operation finishes, or behind the status icon, and a signal then
        // ends it in order.
        HandlesShutdownWithoutWindow = true,
    };

    /// <summary>
    /// Runs the dashboard on its own, without the single instance (no per-user runtime directory, <c>--no-open</c>, or a
    /// running instance for another checkout): shows it in this process until it closes, then waits for an operation
    /// started from it. Ctrl+C or SIGTERM closes the Window and cancels that operation. Call it before any
    /// <see langword="await"/>, since the Desktop host's event loop may need the main thread.
    /// </summary>
    /// <param name="opened">Called with the dashboard Window once it opened, such as to open it in a browser.</param>
    public static int Run(Config config, Action<IRunicWindow>? opened = null) =>
        DesktopEventLoop.Run(HostOptions(), desktop => RunAsync(config, desktop, opened));

    /// <summary>
    /// Runs the dashboard on its own on a Desktop host that runs already, as after the setup assistant created the
    /// checkout (<see cref="Setup.SetupApplication"/>).
    /// </summary>
    /// <param name="opened">Called with the dashboard Window once it opened.</param>
    public static async Task<int> RunAsync(Config config, DesktopHost desktop, Action<IRunicWindow>? opened = null)
    {
        await using var provider = new ServiceCollection()
            .AddNixManagerBackend(config)
            .AddNixManagerDashboard()
            .BuildServiceProvider(new ServiceProviderOptions { ValidateScopes = true, ValidateOnBuild = true });
        var host = new RunicDesktopHost(provider, desktop);
        var service = provider.GetRequiredService<IOperationService>();
        var shutdown = desktop.ShutdownRequested;
        await using (var window = await OpenAsync(host, shutdown))
        {
            opened?.Invoke(window);
            await window.WaitForCloseAsync();
        }
        if (service.Busy)
        {
            Console.Error.WriteLine("The dashboard closed; waiting for the running operation to finish. Press Ctrl+C to cancel it.");
            using (shutdown.Register(service.Cancel))
                await service.WaitAsync();
        }
        return 0;
    }
}

/// <summary>
/// <c>nix-manager ui</c> with its options, recognised before the command line runs, because the Desktop host must
/// start before any <see langword="await"/>. Anything else, such as <c>ui --help</c>, goes to the command line.
/// </summary>
public static class DashboardCommand
{
    /// <summary>Options of <c>ui</c>.</summary>
    /// <param name="Flake">The checkout, from <c>--flake</c>.</param>
    /// <param name="Host">The host, from <c>--host</c>.</param>
    /// <param name="NoOpen">Serve the page without a window (<c>--no-open</c>): Runic's serve-only mode.</param>
    /// <param name="Browser">Serve the page and open it in the default browser (<c>--browser</c>).</param>
    public sealed record Invocation(string? Flake, string? Host, bool NoOpen, bool Browser = false)
    {
        /// <summary>The page is served, not shown in a Window of this application.</summary>
        public bool Served => NoOpen || Browser;
    }

    public static bool TryParse(IReadOnlyList<string> args, out Invocation invocation)
    {
        invocation = new Invocation(null, null, false);
        var ui = false;
        for (var i = 0; i < args.Count; i++)
        {
            var arg = args[i];
            if (string.Equals(arg, "ui", StringComparison.OrdinalIgnoreCase) && !ui) ui = true;
            else if (arg is "--no-open") invocation = invocation with { NoOpen = true };
            else if (arg is "--browser") invocation = invocation with { Browser = true };
            else if (arg is "--plain" or "--verbose") { }
            else if (Value(args, ref i, "--flake") is { } flake) invocation = invocation with { Flake = flake };
            else if (Value(args, ref i, "--host") is { } host) invocation = invocation with { Host = host };
            else return false;
        }
        return ui;
    }

    internal static string? Value(IReadOnlyList<string> args, ref int i, string name)
    {
        if (args[i].StartsWith(name + "=", StringComparison.Ordinal)) return args[i][(name.Length + 1)..];
        if (args[i] != name || i + 1 >= args.Count) return null;
        return args[++i];
    }

    /// <summary>
    /// Opens the dashboard (D025.3): a running instance for this configuration, the daemon or another dashboard, opens
    /// or raises its Window, which shows the running operation. Otherwise this process becomes the running instance
    /// with its Window open, serves command lines like the daemon, and ends once the Window is closed and nothing runs;
    /// the tray takes over the instance after that. Without a per-user runtime directory, with
    /// <c>NIX_MANAGER_DAEMON=0</c>, <c>--no-open</c>, or while an instance runs another checkout, it runs on its own.
    /// </summary>
    /// <remarks>
    /// Without any checkout it starts with the setup assistant, which hands over to the dashboard once it created one;
    /// a dashboard started from the menu (standard output is not a terminal) whose configuration does not load shows
    /// why in the assistant's Window (<c>setUp</c> and <c>main</c> in <c>src/main.ts</c>, <see cref="SetupLaunch"/>).
    /// </remarks>
    public static int Run(Invocation invocation)
    {
        Setup.SetupAssistant.AllowFlakes(ManagerEnvironment.Current);
        if (invocation.Served)
        {
            // The setup assistant, and the dashboard after it, are served the same way; with --browser, the first page
            // opens in the default browser, as the Bun version's did, and the assistant's page moves on by itself.
            Environment.SetEnvironmentVariable("RUNIC_APPLICATION_SERVE_ONLY", "1");
            Action<IRunicWindow>? browse = invocation.Browser ? DashboardBrowser.Open : null;
            if (SetupLaunch.NeedsSetup(invocation.Flake)) return SetupApplication.Run(invocation, named: false, browse);
            if (Daemon.DaemonApplication.Load(invocation.Flake, invocation.Host) is not { } served) return 1;
            return DashboardApplication.Run(served, browse);
        }
        // A dashboard for a checkout or host named here goes to the running instance only if that runs the same one.
        var environment = ManagerEnvironment.Current;
        var named = invocation.Flake is not null || invocation.Host is not null
            || environment.Variable("NIX_MANAGER_FLAKE") is { Length: > 0 } || environment.Variable("NIX_MANAGER_HOST") is { Length: > 0 };
        Config? config = null;
        string? error = null;
        if (named)
        {
            if (SetupLaunch.NeedsSetup(invocation.Flake)) return SetupApplication.Run(invocation, named);
            if ((config = Daemon.DaemonApplication.Load(invocation.Flake, invocation.Host, out error)) is null) return Failed(invocation, error);
        }
        // No event loop runs yet: waiting here keeps the main thread for the Desktop host.
        var claim = Daemon.DaemonProtocol.ClaimAsync(new Daemon.DaemonRequest(Daemon.DaemonRequestKinds.Ui,
            config is null ? null : Daemon.DaemonIdentity.Of(config))).GetAwaiter().GetResult();
        switch (claim)
        {
            case Runic.Platform.ApplicationInstanceClaim.Forwarded { Reply: { } reply }:
                if (Daemon.DaemonApplication.Follow(reply) is { } code) return code;
                break;
            case Runic.Platform.ApplicationInstanceClaim.Primary primary:
                // Before the checkout exists, the assistant runs without the instance; it claims one when it hands over.
                var setup = config is null && SetupLaunch.NeedsSetup(invocation.Flake);
                if (!setup) config ??= Daemon.DaemonApplication.Load(invocation.Flake, invocation.Host, out error);
                if (setup || config is null)
                {
                    primary.Instance.DisposeAsync().AsTask().GetAwaiter().GetResult();
                    return setup ? SetupApplication.Run(invocation, named) : Failed(invocation, error);
                }
                return Daemon.DaemonApplication.Run(config, primary.Instance, new Daemon.DaemonSettings { Mode = Daemon.DaemonMode.Ui });
        }
        if (config is null && SetupLaunch.NeedsSetup(invocation.Flake)) return SetupApplication.Run(invocation, named);
        config ??= Daemon.DaemonApplication.Load(invocation.Flake, invocation.Host, out error);
        return config is null ? Failed(invocation, error) : DashboardApplication.Run(config);
    }

    /// <summary>
    /// The configuration did not load, which loading reported on standard error. Started from the menu, that would go
    /// unseen, so the assistant's Window says why until it is closed.
    /// </summary>
    private static int Failed(Invocation invocation, string? error)
    {
        if (error is not null && SetupLaunch.ShowsProblem(invocation.Served, Console.IsOutputRedirected))
            SetupApplication.ShowProblem(new SetupProblem(error, SetupLaunch.Checkout(invocation.Flake).Path));
        return 1;
    }
}

/// <summary>
/// <c>ui --browser</c>: opens a served page in the desktop's default browser with <c>xdg-open</c>, as the Bun version
/// did. The page stays served until Ctrl+C, SIGTERM or a stop line on standard input, as with <c>--no-open</c>.
/// </summary>
public static class DashboardBrowser
{
    public static void Open(IRunicWindow window)
    {
        var address = window.Host switch
        {
            DesktopBridgeWindow<DashboardViewModel> dashboard => dashboard.Surface.Url.ToString(),
            DesktopBridgeWindow<ViewModels.SetupViewModel> setup => setup.Surface.Url.ToString(),
            _ => null,
        };
        if (address is null) return;
        try
        {
            using var process = System.Diagnostics.Process.Start(new System.Diagnostics.ProcessStartInfo("xdg-open", [address])
            {
                // The served page's stop line arrives on this process's standard input; the browser must not read it.
                RedirectStandardInput = true,
            });
        }
        catch (Exception error) when (error is System.ComponentModel.Win32Exception or InvalidOperationException)
        {
            Console.Error.WriteLine($"Could not open a browser ({error.Message}); open the address above.");
        }
    }
}
