#!/usr/bin/env python3
"""Imports the Bun version's German catalogue (src/locales/de) into the dashboard's Runic Translations.

The Bun version keys its catalogue by English text. This script, run from the repository's development shell:

1. writes translations/stored/{en,de}.rmf2 and src/lib/stored-catalog.ts from the Bun catalogue's `labels` and
   `messages` parts: text the backend stores in English (step labels, errors, failure explanations) and the
   dashboard translates where it shows it (src/lib/i18n.ts); and from its `features` part, the English data
   text of the curated features, starting points and Computer page settings;
2. adds German to translations/de.rmf2 for every message of translations/en.rmf2 that has none yet, taken from
   the Bun catalogue by its English text. Messages already in de.rmf2 are kept as they are, so German written
   there by hand or in the Translations Editor wins.

It reports English text without German. Run it after adding messages to en.rmf2:

    python3 runic/Frontend/scripts/import-bun-catalog.py
"""

import json
import re
import subprocess
import sys
from pathlib import Path

FRONTEND = Path(__file__).resolve().parent.parent
REPOSITORY = FRONTEND.parent.parent
TRANSLATIONS = FRONTEND / "translations"


def bun_catalogue():
    script = 'import { parts } from "./src/locales/de"; console.log(JSON.stringify(parts));'
    output = subprocess.run(["bun", "-e", script], cwd=REPOSITORY, check=True, capture_output=True, text=True).stdout
    return json.loads(output)


def to_pattern(text):
    """Bun text with {name} placeholders as an RMF2 pattern: {$name}, other braces and backslashes escaped."""
    pieces = []
    for token in re.split(r"(\{\w+\})", text):
        if re.fullmatch(r"\{\w+\}", token):
            pieces.append("{$" + token[1:-1] + "}")
        else:
            pieces.append(token.replace("\\", "\\\\").replace("{", "\\{").replace("}", "\\}"))
    pattern = "".join(pieces)
    if "\n" in pattern or pattern != pattern.strip() or pattern.startswith("."):
        raise ValueError(f"Text needs a quoted pattern: {text!r}")
    return pattern


def from_pattern(pattern):
    """The Bun form of an RMF2 pattern: {$name} as {name}, escapes removed."""
    text = re.sub(r"\{\$(\w+)(?: :\w+)?\}", r"{\1}", pattern)
    return re.sub(r"\\(.)", r"\1", text)


def slug(text, taken):
    words = re.findall(r"[a-z0-9]+", re.sub(r"\{\w+\}", "", text.lower()))[:7] or ["text"]
    base = "_".join(words)
    if base[0].isdigit():
        base = "n_" + base
    key, number = base, 2
    while key in taken:
        key, number = f"{base}_{number}", number + 1
    taken.add(key)
    return key


def write_stored(catalogue):
    # Data text after the stored text: the curated features, starting points and Computer page settings
    # (src/lib/curated.ts, bundles.ts, computer.ts, apps.ts) are English and translated where they are shown.
    english_to_german = {**catalogue["labels"], **catalogue["messages"], **catalogue["features"]}
    taken, rows = set(), []
    for english, german in english_to_german.items():
        rows.append((slug(english, taken), english, german))
    header = "# Generated by scripts/import-bun-catalog.py from the Bun version's labels and messages; do not edit.\n"
    directory = TRANSLATIONS / "stored"
    directory.mkdir(exist_ok=True)
    for locale, column in (("en", 1), ("de", 2)):
        lines = [header] + [f"{row[0]} = {to_pattern(row[column])}\n" for row in rows]
        (directory / f"{locale}.rmf2").write_text("".join(lines))
    table = "".join(f"  [{json.dumps('stored_' + key)}, {json.dumps(english, ensure_ascii=False)}],\n" for key, english, _ in rows)
    (FRONTEND / "src/lib/stored-catalog.ts").write_text(
        "// Generated by scripts/import-bun-catalog.py; do not edit.\n"
        "// Text the backend stores in English, by the key of its message in translations/stored.\n"
        f"export const storedMessages: readonly (readonly [string, string])[] = [\n{table}];\n"
    )
    return len(rows)


ENTRY = re.compile(r"^  ([A-Za-z_][A-Za-z0-9_]*) =(.*)$")
GROUP = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*) \{$")


def entries(path):
    """The entries of a .rmf2 file in this project's layout, in order: (key, lines), or (None, line) for other
    lines. Groups open at column 0 (`name {`) and close with `}`; entries are indented by two spaces, and the
    lines of a multi-line entry by four."""
    group, key = None, None
    for line in path.read_text().splitlines() if path.exists() else []:
        if match := GROUP.match(line):
            group, key = match.group(1), None
            yield None, line
        elif line == "}":
            group, key = None, None
            yield None, line
        elif match := ENTRY.match(line):
            key = f"{group}_{match.group(1)}"
            yield key, [line]
        elif key is not None and line.startswith("    "):
            yield key, line
        else:
            key = None
            yield None, line


def parse(path):
    messages = {}
    for key, value in entries(path):
        if key is None:
            continue
        if isinstance(value, list):
            messages[key] = value
        else:
            messages[key].append(value)
    return messages


def annotate(pattern, english):
    """`pattern` with the functions the English pattern gives its placeholders, such as {$count :integer}."""
    functions = dict(re.findall(r"\{\$(\w+) (:\w+)\}", english))
    return re.sub(r"\{\$(\w+)\}", lambda match: "{$" + match.group(1) + (" " + functions[match.group(1)] if match.group(1) in functions else "") + "}", pattern)


def german_entry(lines, german):
    """The German lines of an English entry, or None when the catalogue lacks one of its texts."""
    first = ENTRY.match(lines[0])
    if first.group(2).strip():
        english = first.group(2).strip()
        text = german.get(from_pattern(english))
        return None if text is None else [f"  {first.group(1)} = {annotate(to_pattern(text), english)}"]
    result = [lines[0]]
    for line in lines[1:]:
        variant = re.match(r"^(\s*)((?:\S+ )?)\{\{(.*)\}\}$", line)
        if variant:
            text = german.get(from_pattern(variant.group(3)))
            if text is None:
                return None
            result.append(f"{variant.group(1)}{variant.group(2)}{{{{{annotate(to_pattern(text), variant.group(3))}}}}}")
        else:
            result.append(line)
    return result


def fill_german(catalogue):
    german = {}
    for part in catalogue.values():
        german.update(part)
    english = parse(TRANSLATIONS / "en.rmf2")
    existing = parse(TRANSLATIONS / "de.rmf2")
    missing, output = [], []
    for key, value in entries(TRANSLATIONS / "en.rmf2"):
        if key is None:
            # Comments describe the English entries; the German file keeps only the structure.
            if not value.lstrip().startswith(("#", "@")):
                output.append(value)
        elif isinstance(value, list):
            entry = existing.get(key) or german_entry(english[key], german)
            if entry is None:
                missing.append(key)
            else:
                output.extend(entry)
    (TRANSLATIONS / "de.rmf2").write_text("\n".join(output) + "\n")
    return missing


def main():
    catalogue = bun_catalogue()
    count = write_stored(catalogue)
    missing = fill_german(catalogue)
    print(f"Stored messages: {count}.")
    if missing:
        print("No German for these messages of en.rmf2; add them to de.rmf2:", file=sys.stderr)
        for key in missing:
            print(f"  {key}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
